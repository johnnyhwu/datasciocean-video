def paper_row(scores, dim_idx=(), medal=False):
    g = VGroup()
    for i, s in enumerate(scores):
        pap = RoundedRectangle(corner_radius=.08, width=.95, height=1.2).set_fill(PANEL, 1).set_stroke(MUTED, 2)
        it = VGroup(pap, B(str(s), .06, INK).move_to(pap))
        if i in dim_idx:
            it.set_opacity(.3)
        g.add(it)
    g.arrange(RIGHT, buff=.45).move_to(ROW_C)
    if medal:
        rib = VGroup(Polygon(LEFT * .2 + UP * .2, LEFT * .02 + UP * .2, LEFT * .12 + DOWN * .15).set_fill(BAD, 1).set_stroke(width=0),
                     Polygon(RIGHT * .2 + UP * .2, RIGHT * .02 + UP * .2, RIGHT * .12 + DOWN * .15).set_fill(DIST, 1).set_stroke(width=0))
        med = VGroup(rib, Circle(.26).set_fill(ARG, 1).set_stroke(GOLD, 3)).arrange(DOWN, buff=-.08)
        m = VGroup(med, T("獎勵", .038, TXT)).arrange(DOWN, buff=.12)
        m.next_to(g[0], LEFT, buff=.45)
        g.add(m)
    return g


